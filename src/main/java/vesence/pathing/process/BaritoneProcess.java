package vesence.pathing.process;

import net.fabricmc.api.EnvType;
import net.fabricmc.api.Environment;

/**
 * Задача Baritone: то, что выполняется поверх поиска пути.
 *
 * <p>Ходьба сама по себе — только половина дела. Настоящий Baritone умеет ещё
 * копать, собирать урожай, ходить за игроком и исследовать мир. Каждая такая
 * задача — отдельный процесс: он сам решает, куда идти, сам ставит цель поиску
 * пути и сам решает, когда закончил.
 *
 * <p>Процессов одновременно активен максимум один. Это то же правило, что и в
 * Baritone: две задачи, дёргающие цель туда-сюда, — это гарантированный ступор.
 */
@Environment(EnvType.CLIENT)
public interface BaritoneProcess {

    /** Имя для сообщений игроку и {@code .status}. */
    String name();

    /** Ещё работает? Как только вернёт {@code false}, движок снимет процесс. */
    boolean isActive();

    /**
     * Один тик. Здесь процесс ставит цели поиску пути и делает свою работу
     * (например, ломает блок).
     */
    void tick();

    /**
     * Поиск пути не смог добраться до поставленной цели.
     *
     * <p>Вызывается вместо сообщения «не удалось дойти»: у процесса на такой
     * случай есть свой план — например, вычеркнуть блок и взяться за следующий.
     * Если бы движок в этот момент писал в чат и снимал процесс, ферма
     * останавливалась бы на первом же недостижимом блоке и засыпала игрока
     * сообщениями об остановке.
     */
    default void onPathFailed() {
    }

    /** Освободить ресурсы: остановить ломание, отпустить цель. */
    default void cancel() {
    }
}

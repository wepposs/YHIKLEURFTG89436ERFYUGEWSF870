    private static final Minecraft mc = Minecraft.getInstance();
    private static final Random RNG = new Random();
    private static final int DELAY_TICKS = 50; // 2.5 сек

    private int tickCounter = 0;
    private String lastSent = null;
    private boolean registered = false;

    public AutoTroll() {
        this.addSettings(new Setting[]{ name, antiDuplicate, withName, phrases });

        // Один раз регистрируемся на Fabric-тик. Внутри проверяем enable,
        // чтобы модуль не отправлял ничего выключенным.
        if (!registered) {
            registered = true;
            ClientTickEvents.END_CLIENT_TICK.register(client -> {
                if (!this.enable) return;
                if (++tickCounter < DELAY_TICKS) return;
                tickCounter = 0;
                if (mc.getConnection() == null) return;

                String body = pickPhrase();
                if (body == null || body.isEmpty()) return;

                String nick = name.get() == null ? "" : name.get().trim();
                String outgoing = (withName.get() && !nick.isEmpty()) ? "!" + nick + " " + body : "!" + body;

                if (antiDuplicate.get() && outgoing.equals(lastSent)) {
                    String alt = pickPhrase();
                    if (alt != null && !alt.isEmpty()) {
                        outgoing = (withName.get() && !nick.isEmpty()) ? "!" + nick + " " + alt : "!" + alt;
                    }
                }

                mc.getConnection().sendChat(outgoing);
                lastSent = outgoing;
            });
        }
    }

    private String pickPhrase() {
        Object raw = phrases.get();

        if (raw instanceof String[] arr) {
            if (arr.length > 0) return arr[RNG.nextInt(arr.length)];
        } else if (raw instanceof java.util.List<?> list) {
            if (!list.isEmpty()) return String.valueOf(list.get(RNG.nextInt(list.size())));
        } else if (raw instanceof String s) {
            if (!s.isEmpty()) return s;
        }

        for (String fieldName : new String[]{ "selected", "list", "options", "values" }) {
            try {
                java.lang.reflect.Field f = phrases.getClass().getField(fieldName);
                Object v = f.get(phrases);
                if (v instanceof java.util.List<?> l && !l.isEmpty()) {
                    return String.valueOf(l.get(RNG.nextInt(l.size())));
                }
                if (v instanceof String[] a && a.length > 0) {
                    return a[RNG.nextInt(a.length)];
                }
            } catch (Throwable ignored) {}
        }

        return null;
    }
